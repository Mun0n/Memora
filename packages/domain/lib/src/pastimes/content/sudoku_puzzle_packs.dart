/// One reviewed Sudoku board: clues (0 = empty) and unique solution.
///
/// Runtime may rotate/reflect from a seed but must not publish unverified grids.
final class SudokuReviewedBoard {
  const SudokuReviewedBoard({
    required this.packId,
    required this.boardSize,
    required this.clues,
    required this.solution,
  });

  final String packId;
  final SudokuBoardSize boardSize;
  final List<int> clues;
  final List<int> solution;

  int get dimension => boardSize.dimension;

  int get cellCount => dimension * dimension;
}

